import React from "react";
import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";
import { render, screen, fireEvent, waitFor, within } from "@testing-library/react";
import { axe, toHaveNoViolations } from "jest-axe";
import { IdeasView } from "../../src/components/ideas/IdeasView";
import { AnnounceProvider } from "../../src/components/shell/AnnounceContext";
import { PlannedEvent } from "../../src/lib/domain";
import * as storage from "../../src/lib/storage";

expect.extend(toHaveNoViolations);

const sampleEvent: PlannedEvent = {
  brief: {
    id: "f8d8c366-0275-4ee6-8575-cf6d1fb525f2",
    name: "Rohan & Priya's Sangeet",
    type: "wedding",
    date: "2026-11-20",
    guestCount: 150,
    totalBudget: 1200000,
    currency: "INR",
    city: "Mumbai",
    cityTier: "metro",
    venueType: "indoor",
    priorities: ["food", "entertainment"],
    dietaryNeeds: ["Vegetarian", "Jain"],
  },
  budgetLines: [],
  tasks: [],
  vendors: [],
  guests: [],
  ideas: [
    {
      id: "saved-1",
      title: "Royal Rajwada Welcome Drink",
      description: "Chilled saffron almond thandai served in brass tumblers.",
      tag: "Hospitality",
      saved: true,
    },
  ],
  schemaVersion: 1,
};

const mockGeneratedIdeas = [
  {
    title: "Live Sitar & Cello Fusion Entrance",
    description: "Welcome guests with classical ragas arranged over gentle cello melodies.",
    tag: "Music",
    estimatedCost: "medium",
  },
  {
    title: "Interactive Chaat Cart",
    description: "Chef-driven live chaat counter with pani puri flight pairings.",
    tag: "Catering",
    estimatedCost: "low",
  },
  {
    title: "Hand-Block Printed Napkins",
    description: "Custom artisanal floral motifs matching table textiles.",
    tag: "Décor",
    estimatedCost: "low",
  },
  {
    title: "Starlight Ceiling Installation",
    description: "Warm fairy light canopy creating an indoor night sky illusion.",
    tag: "Lighting",
    estimatedCost: "high",
  },
  {
    title: "Surprise Flash Choreography",
    description: "Coordinated family entrance dance culminating with the couple.",
    tag: "Surprise",
    estimatedCost: "low",
  },
];

function renderIdeas(event = sampleEvent) {
  return render(
    <AnnounceProvider>
      <IdeasView event={event} />
    </AnnounceProvider>
  );
}

describe("Ideas Page (/events/[id]/ideas)", () => {
  beforeEach(() => {
    vi.restoreAllMocks();
    vi.spyOn(storage, "updateEvent").mockReturnValue({ ok: true, data: sampleEvent });
  });

  afterEach(() => {
    vi.restoreAllMocks();
  });

  it("renders lead explanation with event parameters and privacy note", () => {
    renderIdeas();

    expect(screen.getByRole("heading", { level: 1 })).toHaveTextContent(
      "Celebration Ideas & Creative Concepts"
    );
    expect(
      screen.getByText(/Personalized suggestions are crafted using your event type/i)
    ).toBeInTheDocument();
    expect(
      screen.getByText(/Guest privacy: Guest names and contact details are strictly kept in this browser/i)
    ).toBeInTheDocument();
  });

  it("handles successful AI generation with unequal hierarchy and saves ideas to store", async () => {
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      status: 200,
      json: async () => ({
        ideas: mockGeneratedIdeas,
        source: "ai",
      }),
    } as unknown as Response);

    renderIdeas();

    // Fill mood input
    const moodInput = screen.getByLabelText(/Mood \/ Aesthetic/i);
    fireEvent.change(moodInput, { target: { value: "Regal vintage" } });

    // Submit form
    const submitBtn = screen.getByRole("button", { name: /Generate ideas/i });
    fireEvent.click(submitBtn);

    // Verify loading status state
    expect(screen.getByTestId("ideas-generating-status")).toHaveTextContent("Generating ideas…");

    // Wait for ideas to render
    await waitFor(() => {
      expect(screen.getByText("Suggestions generated by AI. Verify costs and feasibility.")).toBeInTheDocument();
    });

    // Check unequal hierarchy: lead entry + supporting entries
    expect(screen.getByText("Live Sitar & Cello Fusion Entrance")).toBeInTheDocument();
    expect(screen.getByText("Interactive Chaat Cart")).toBeInTheDocument();

    // Save lead idea
    const saveButtons = screen.getAllByRole("button", { name: /Save idea/i });
    fireEvent.click(saveButtons[0]);

    expect(storage.updateEvent).toHaveBeenCalledWith(
      sampleEvent.brief.id,
      expect.objectContaining({
        ideas: expect.arrayContaining([
          expect.objectContaining({
            title: "Live Sitar & Cello Fusion Entrance",
            saved: true,
          }),
        ]),
      })
    );
  });

  it("displays fallback honesty note when source is fallback", async () => {
    global.fetch = vi.fn().mockResolvedValue({
      ok: true,
      status: 200,
      json: async () => ({
        ideas: mockGeneratedIdeas,
        source: "fallback",
      }),
    } as unknown as Response);

    renderIdeas();

    fireEvent.click(screen.getByRole("button", { name: /Generate ideas/i }));

    await waitFor(() => {
      expect(
        screen.getByText("AI is unavailable right now, so these are general suggestions for your event type.")
      ).toBeInTheDocument();
    });
  });

  it("shows friendly rate-limit message with retry button on 429", async () => {
    global.fetch = vi.fn().mockResolvedValue({
      ok: false,
      status: 429,
      json: async () => ({ error: "Too many requests" }),
    } as unknown as Response);

    renderIdeas();

    fireEvent.click(screen.getByRole("button", { name: /Generate ideas/i }));

    await waitFor(() => {
      const alert = screen.getByTestId("ideas-error-alert");
      expect(alert).toHaveTextContent("We've hit a temporary rate limit. Please wait a moment and try again.");
    });

    expect(screen.getByRole("button", { name: /Retry/i })).toBeInTheDocument();
  });

  it("handles network failure cleanly with friendly message", async () => {
    global.fetch = vi.fn().mockRejectedValue(new Error("Failed to fetch"));

    renderIdeas();

    fireEvent.click(screen.getByRole("button", { name: /Generate ideas/i }));

    await waitFor(() => {
      const alert = screen.getByTestId("ideas-error-alert");
      expect(alert).toHaveTextContent("Network connection error. Please check your connection and retry.");
    });
  });

  it("shows pinned saved ideas and allows removing them", () => {
    renderIdeas();

    // Pinned scrapbook shows 1 saved idea initially
    expect(screen.getByText("Saved Ideas (1)")).toBeInTheDocument();
    expect(screen.getByText("Royal Rajwada Welcome Drink")).toBeInTheDocument();

    const removeBtn = screen.getByRole("button", { name: /Remove Royal Rajwada Welcome Drink from saved/i });
    fireEvent.click(removeBtn);

    expect(storage.updateEvent).toHaveBeenCalledWith(
      sampleEvent.brief.id,
      expect.objectContaining({
        ideas: expect.arrayContaining([
          expect.objectContaining({
            title: "Royal Rajwada Welcome Drink",
            saved: false,
          }),
        ]),
      })
    );
  });

  it("passes accessibility scan with zero violations", async () => {
    const { container } = renderIdeas();
    const results = await axe(container);
    expect(results).toHaveNoViolations();
  });
});
